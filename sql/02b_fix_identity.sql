-- 02B: SỬA CỘT IDENTITY cho các bảng nằm trong Duality View
-- Dùng khi đã chạy 02_tables.sql bản cũ (GENERATED ALWAYS) và gặp ORA-32795.
-- Chạy bằng ecom_schema. Không mất dữ liệu.
-- ==============================================================================
ALTER TABLE customers          MODIFY customer_id   GENERATED BY DEFAULT ON NULL AS IDENTITY;
ALTER TABLE customer_addresses MODIFY address_id    GENERATED BY DEFAULT ON NULL AS IDENTITY;
ALTER TABLE sellers            MODIFY seller_id     GENERATED BY DEFAULT ON NULL AS IDENTITY;
ALTER TABLE categories         MODIFY category_id   GENERATED BY DEFAULT ON NULL AS IDENTITY;
ALTER TABLE products           MODIFY product_id    GENERATED BY DEFAULT ON NULL AS IDENTITY;
ALTER TABLE orders             MODIFY order_id      GENERATED BY DEFAULT ON NULL AS IDENTITY;
ALTER TABLE order_items        MODIFY order_item_id GENERATED BY DEFAULT ON NULL AS IDENTITY;
ALTER TABLE payments           MODIFY payment_id    GENERATED BY DEFAULT ON NULL AS IDENTITY;
ALTER TABLE shipments          MODIFY shipment_id   GENERATED BY DEFAULT ON NULL AS IDENTITY;
ALTER TABLE order_status_history MODIFY history_id  GENERATED BY DEFAULT ON NULL AS IDENTITY;
