CREATE OR REPLACE TRIGGER trg_pay_check
FOR INSERT OR UPDATE ON payments
COMPOUND TRIGGER
  TYPE t_ids IS TABLE OF NUMBER INDEX BY VARCHAR2(20);
  g_orders t_ids;

  -- Chỉ ghi nhận đơn có dòng thanh toán ĐANG ở trạng thái PAID: chỉ khi đó tổng đã trả mới có thể
  -- tăng và vượt total_amount. Dòng chuyển sang REFUNDED/FAILED chỉ làm tổng đã trả giảm -> không
  -- cần kiểm tra. Điều này cũng tránh ORA-04091: khi huỷ đơn, trigger của orders gọi
  -- sp_refund_order_payments (UPDATE payments) trong lúc bảng orders đang "mutating"; nếu ở đây
  -- vẫn SELECT ... FROM orders thì sẽ lỗi.
  AFTER EACH ROW IS
  BEGIN
    IF :NEW.status = 'PAID' THEN
      g_orders(TO_CHAR(:NEW.order_id)) := :NEW.order_id;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
    l_key   VARCHAR2(20) := g_orders.FIRST;
    l_total orders.total_amount%TYPE;
    l_paid  NUMBER;
  BEGIN
    WHILE l_key IS NOT NULL LOOP
      SELECT total_amount INTO l_total FROM orders
       WHERE order_id = g_orders(l_key) FOR UPDATE;
      SELECT NVL(SUM(amount), 0) INTO l_paid FROM payments
       WHERE order_id = g_orders(l_key) AND status = 'PAID';
      IF l_paid > l_total THEN
        RAISE_APPLICATION_ERROR(-20005, 'Tổng thanh toán vượt tổng tiền đơn');
      END IF;
      l_key := g_orders.NEXT(l_key);
    END LOOP;
    g_orders.DELETE;
  END AFTER STATEMENT;
END trg_pay_check;
