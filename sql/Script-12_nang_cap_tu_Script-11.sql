  FUNCTION fn_r6_revenue_by_brand RETURN SYS_REFCURSOR;

  -- ---- Thống kê cho MỘT người bán (trang "Thống kê shop"); doanh thu = tiền hàng của shop trong đơn DELIVERED ----
