CREATE SEQUENCE seq_order_no START WITH 1 CACHE 100;

CREATE TABLE customers (
  customer_id  NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  full_name    VARCHAR2(100) NOT NULL,
  email        VARCHAR2(120) NOT NULL,
  phone        VARCHAR2(20),
  status       VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT customers_email_uq  UNIQUE (email),
  CONSTRAINT customers_status_ck CHECK (status IN ('ACTIVE','LOCKED'))
);

CREATE TABLE customer_addresses (
  address_id     NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  customer_id    NUMBER(12) NOT NULL REFERENCES customers (customer_id) ON DELETE CASCADE,
  receiver_name  VARCHAR2(100) NOT NULL,
  receiver_phone VARCHAR2(20)  NOT NULL,
  address_line   VARCHAR2(200) NOT NULL,
  ward           VARCHAR2(60),
  district       VARCHAR2(60),
  city           VARCHAR2(60)  NOT NULL,
  is_default     NUMBER(1) DEFAULT 0 NOT NULL,
  CONSTRAINT cust_addr_default_ck CHECK (is_default IN (0,1))
);

CREATE TABLE sellers (
  seller_id  NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  shop_name  VARCHAR2(120) NOT NULL,
  email      VARCHAR2(120) NOT NULL,
  phone      VARCHAR2(20),
  status     VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
  joined_at  TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT sellers_email_uq  UNIQUE (email),
  CONSTRAINT sellers_status_ck CHECK (status IN ('ACTIVE','SUSPENDED'))
);

CREATE TABLE categories (
  category_id   NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  parent_id     NUMBER(12) REFERENCES categories (category_id),
  category_name VARCHAR2(100) NOT NULL
);

CREATE TABLE products (
  product_id   NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  seller_id    NUMBER(12) NOT NULL REFERENCES sellers (seller_id),
  category_id  NUMBER(12) NOT NULL REFERENCES categories (category_id),
  sku          VARCHAR2(40)  NOT NULL,
  product_name VARCHAR2(200) NOT NULL,
  price        NUMBER(14,2)  NOT NULL,
  stock_qty    NUMBER(8)     DEFAULT 0 NOT NULL,
  -- Thuộc tính linh hoạt theo ngành hàng, lưu JSON. JSON Schema khai báo NGAY TRÊN KIỂU CỘT
  -- (cú pháp 23ai "JSON VALIDATE '<schema>'"): bắt buộc là object, phải có "brand" (chuỗi),
  -- nếu có "warrantyMonths" thì phải là số >= 0. Vi phạm -> ORA-40875.
  -- LÝ DO không dùng "CHECK (attributes IS JSON VALIDATE ...)" như bản đầu: kiểm thử trên
  -- 23.26.3 cho thấy ràng buộc CHECK rời đó BỊ BỎ QUA khi ghi qua PRODUCT_DV (INSERT trực
  -- tiếp thì bị chặn), còn khai báo trên kiểu cột thì chặn được cả hai kênh (TC-11).
  attributes   JSON CONSTRAINT products_attr_chk VALIDATE '{
                  "type"       : "object",
                  "properties" : {
                    "brand"          : { "type" : "string" },
                    "warrantyMonths" : { "type" : "number", "minimum" : 0 }
                  },
                  "required"   : [ "brand" ]
                }',
  status       VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT products_sku_uq    UNIQUE (sku),
  CONSTRAINT products_price_ck  CHECK (price >= 0),
  CONSTRAINT products_stock_ck  CHECK (stock_qty >= 0),
  CONSTRAINT products_status_ck CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE orders (
  order_id        NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  order_no        VARCHAR2(30)  NOT NULL,
  customer_id     NUMBER(12)    NOT NULL REFERENCES customers (customer_id),
  status          VARCHAR2(12)  DEFAULT 'PENDING' NOT NULL,
  order_date      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  ship_receiver   VARCHAR2(100) NOT NULL,
  ship_phone      VARCHAR2(20)  NOT NULL,
  ship_address    VARCHAR2(400) NOT NULL,
  subtotal        NUMBER(14,2)  DEFAULT 0 NOT NULL,
  shipping_fee    NUMBER(14,2)  DEFAULT 0 NOT NULL,
  discount_amount NUMBER(14,2)  DEFAULT 0 NOT NULL,
  total_amount    NUMBER(14,2)  DEFAULT 0 NOT NULL,
  note            VARCHAR2(500),
  updated_at      TIMESTAMP,
  CONSTRAINT orders_no_uq     UNIQUE (order_no),
  CONSTRAINT orders_status_ck CHECK (status IN ('PENDING','CONFIRMED','PACKING',
                                      'SHIPPING','DELIVERED','CANCELLED','RETURNED')),
  CONSTRAINT orders_money_ck  CHECK (subtotal >= 0 AND shipping_fee >= 0
                                      AND discount_amount >= 0 AND total_amount >= 0)
);

CREATE TABLE order_items (
  order_item_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  order_id      NUMBER(12)   NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
  product_id    NUMBER(12)   NOT NULL REFERENCES products (product_id),
  quantity      NUMBER(6)    NOT NULL CHECK (quantity > 0),
  unit_price    NUMBER(14,2) NOT NULL CHECK (unit_price >= 0),
  CONSTRAINT order_items_uq UNIQUE (order_id, product_id)
);

CREATE TABLE payments (
  payment_id      NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  order_id        NUMBER(12)   NOT NULL REFERENCES orders (order_id),
  method          VARCHAR2(20) NOT NULL,
  amount          NUMBER(14,2) NOT NULL,
  status          VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
  paid_at         TIMESTAMP,
  transaction_ref VARCHAR2(60),
  CONSTRAINT payments_method_ck CHECK (method IN ('COD','BANK_TRANSFER','E_WALLET','CARD')),
  CONSTRAINT payments_amount_ck CHECK (amount > 0),
  CONSTRAINT payments_status_ck CHECK (status IN ('PENDING','PAID','FAILED','REFUNDED'))
);

CREATE TABLE shipments (
  shipment_id  NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  order_id     NUMBER(12)   NOT NULL REFERENCES orders (order_id),
  carrier      VARCHAR2(60) NOT NULL,
  tracking_no  VARCHAR2(60),
  status       VARCHAR2(12) DEFAULT 'PREPARING' NOT NULL,
  shipped_at   TIMESTAMP,
  delivered_at TIMESTAMP,
  CONSTRAINT shipments_status_ck CHECK (status IN ('PREPARING','IN_TRANSIT','DELIVERED','RETURNED'))
);

CREATE TABLE order_status_history (
  history_id NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  order_id   NUMBER(12)   NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
  old_status VARCHAR2(12),
  new_status VARCHAR2(12) NOT NULL,
  changed_at TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  changed_by VARCHAR2(60),
  note       VARCHAR2(300)
);
