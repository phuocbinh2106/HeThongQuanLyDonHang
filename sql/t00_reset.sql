--   Bước 1 (file này): xoá sạch dữ liệu 10 bảng, đặt lại identity và seq_order_no về 1.
--   Bước 2: chạy 08_seed.sql để nạp lại dữ liệu mẫu.
-- SQL*Plus/SQLcl: file này tự gọi 08_seed.sql ở cuối.
-- DBeaver: chạy file này (Alt+X), rồi mở và chạy tiếp 08_seed.sql.
--
-- Vì sao dùng TRUNCATE + tắt khoá ngoại, không dùng DELETE?
--   DELETE order_items của đơn đã CONFIRMED sẽ bị trigger trg_oi_biud_row chặn (ORA-20004)
--   và DELETE sẽ kích hoạt trigger hoàn kho. TRUNCATE không kích hoạt trigger DML.
--   Nhưng không TRUNCATE được bảng cha khi còn khoá ngoại đang bật trỏ tới (ORA-02266),
--   nên phải tắt các khoá ngoại trước rồi bật lại sau.
-- ==============================================================================
SET SERVEROUTPUT ON
DECLARE
  TYPE t_names IS TABLE OF VARCHAR2(128);
  -- con trước, cha sau
  l_tables t_names := t_names('ORDER_STATUS_HISTORY','SHIPMENTS','PAYMENTS','ORDER_ITEMS',
                              'ORDERS','CUSTOMER_ADDRESSES','CUSTOMERS','PRODUCTS',
                              'CATEGORIES','SELLERS');
BEGIN
  -- 1) Tắt mọi khoá ngoại
  FOR r IN (SELECT table_name, constraint_name FROM user_constraints
             WHERE constraint_type = 'R' AND status = 'ENABLED') LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE ' || r.table_name || ' DISABLE CONSTRAINT ' || r.constraint_name;
  END LOOP;

  -- 2) Xoá dữ liệu
  FOR i IN 1 .. l_tables.COUNT LOOP
    EXECUTE IMMEDIATE 'TRUNCATE TABLE ' || l_tables(i);
  END LOOP;

  -- 3) Bật lại khoá ngoại
  FOR r IN (SELECT table_name, constraint_name FROM user_constraints
             WHERE constraint_type = 'R' AND status = 'DISABLED') LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE ' || r.table_name || ' ENABLE CONSTRAINT ' || r.constraint_name;
  END LOOP;

  -- 4) Đặt lại cột identity bắt đầu từ 1
  FOR r IN (SELECT table_name, column_name FROM user_tab_identity_cols) LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE ' || r.table_name || ' MODIFY ' || r.column_name
                   || ' GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1)';
  END LOOP;

  -- 5) Đặt lại sequence sinh số đơn
  EXECUTE IMMEDIATE 'ALTER SEQUENCE seq_order_no RESTART START WITH 1';

  -- 6) Biến trạng thái của package về mặc định
  pkg_order.g_internal := FALSE;
  DBMS_OUTPUT.PUT_LINE('Đã xoá dữ liệu. Tiếp theo: chạy 08_seed.sql');
END;
